/**
 * Prompt 3: Schema → Entity Instantiation
 * 
 * This prompt is used to generate canonical names and aliases for entities.
 * It is used in 50% of entity instantiations (random sampling) to balance
 * accuracy and token consumption.
 * 
 * Design Reference: Phase 2 - Prompt Module, Section 5 - Entity Builder (Enhanced with LLM)
 * Requirements: 4.3, 4.4, 11.5
 */

/**
 * Build entity name standardization prompt for LLM
 * 
 * This prompt should be used when:
 * 1. Random sampling (50% probability) for quality improvement
 * 2. Entity name is not well-formed (contains special chars, inconsistent format)
 * 3. Entity name needs disambiguation (multiple possible interpretations)
 * 
 * @param {string} rawName - Raw entity name generated by rules
 * @param {string} entityType - Type of entity (EventEntity, LocationEntity, etc.)
 * @param {Object} context - Additional context
 * @param {string} context.text - Original text from CKB
 * @param {Array} context.fields - Extracted fields
 * @param {Object} context.schema - Schema that triggered entity creation
 * @param {Object} options - Additional options
 * @param {boolean} options.includeExamples - Whether to include examples
 * @param {number} options.maxAliases - Maximum number of aliases to generate (default: 3)
 * @returns {string} Complete prompt for LLM
 */
function buildEntityNamePrompt(rawName, entityType, context = {}, options = {}) {
  const {
    includeExamples = true,
    maxAliases = 3
  } = options;

  // Build context section
  const contextSection = buildContextSection(context);
  
  // Build entity type guidance
  const entityTypeSection = buildEntityTypeSection(entityType);
  
  // Build examples section
  const examplesSection = includeExamples ? buildExamplesSection() : '';
  
  // Build constraints section
  const constraintsSection = buildConstraintsSection();

  return `你是一个知识图谱实体标准化专家。你的任务是为实体生成规范的名称和常见别名。

## 原始实体名称
${rawName}

## 实体类型
${entityType}

${contextSection}

${entityTypeSection}

## 任务要求
1. 生成一个规范的实体名称（canonical_name）
2. 生成 2-${maxAliases} 个常见别名（aliases）
3. 规范名称应该：
   - 去除冗余词汇（如"的"、"了"等）
   - 统一格式（如"阿里C区" vs "阿里 C 区"）
   - 保持简洁明确
   - 符合该实体类型的命名规范
4. 别名应该包括：
   - 常见的简称或缩写
   - 不同的表述方式
   - 可能的同义词
5. **只基于原始文本和已提取字段，不要推理或创造新信息**

${examplesSection}

${constraintsSection}

## 输出格式
请严格按照以下 JSON 格式输出，不要包含其他文字：

{
  "canonical_name": "规范的实体名称",
  "aliases": ["别名1", "别名2", "别名3"],
  "reasoning": "简短说明标准化的理由"
}`;
}

/**
 * Build context section
 * @param {Object} context - Context information
 * @returns {string} Formatted section
 */
function buildContextSection(context) {
  if (!context || (!context.text && !context.fields)) {
    return '';
  }
  
  let section = '';
  
  if (context.text) {
    section += `## 原始文本\n${context.text}\n\n`;
  }
  
  if (context.fields && context.fields.length > 0) {
    const fieldsList = context.fields
      .map(f => `- ${f.name}: ${f.value} (${f.type})`)
      .join('\n');
    section += `## 提取的字段\n${fieldsList}\n\n`;
  }
  
  if (context.schema) {
    section += `## 触发的 Schema\n${context.schema.schema_name}\n\n`;
  }
  
  return section;
}

