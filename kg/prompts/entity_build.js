/**
 * Build constraints section
 * @returns {string} Formatted section with constraints
 */
function buildConstraintsSection() {
  return `## 重要约束

1. **基于原文**：只基于原始文本和已提取字段进行标准化，不要创造新信息
   - ❌ 错误：原文说"水位下降"，不要推理出"可能导致干旱"并添加到名称中
   - ✅ 正确：只标准化"水位下降"这个事实

2. **保持语义**：规范名称必须保持原始名称的核心语义
   - ❌ 错误：将"水位下降"改为"水位变化"（改变了方向性）
   - ✅ 正确：将"水位下降了"改为"水位下降"（去除冗余词）

3. **别名质量**：
   - 别名必须是该实体的真实别称，不是相关实体
   - 别名应该是常见的、自然的表述
   - 避免生成过于相似的别名（如"阿里C区"和"阿里 C 区"）
   - 如果实在找不到合适的别名，可以少于最大数量

4. **格式统一**：
   - 去除多余空格（"阿里 C 区" → "阿里C区"）
   - 去除冗余标点（"水位下降！" → "水位下降"）
   - 统一日期格式（"2025年1月" → "2025-01"）
   - 去除冗余词汇（"的"、"了"、"事件"等）

5. **实体类型一致性**：
   - 规范名称和别名必须符合实体类型的命名规范
   - 不要混淆不同类型的实体（如将事件名称用于地点实体）

6. **简洁性**：
   - 规范名称应该简洁明确，通常不超过 20 个字符
   - 避免过长的描述性名称
   - 如果原始名称已经很简洁，可以保持不变

7. **推理说明**：
   - reasoning 字段应简短（1-2句话）
   - 说明主要的标准化操作（去除了什么、统一了什么、为什么这样命名）
   - 对于已经规范的名称，说明"原始名称已规范"`;
}

