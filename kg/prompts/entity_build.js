/**
 * Build entity disambiguation prompt for LLM
 * 
 * This prompt is used to determine if two entities are the same entity
 * with different names (30% probability sampling for cost control).
 * 
 * @param {Object} entity1 - First entity
 * @param {string} entity1.canonical_name - Canonical name
 * @param {Array} entity1.aliases - Aliases
 * @param {Object} entity1.attributes - Attributes
 * @param {Object} entity2 - Second entity (same structure as entity1)
 * @param {Object} options - Additional options
 * @param {boolean} options.includeExamples - Whether to include examples
 * @returns {string} Complete prompt for LLM
 */
function buildEntityDisambiguationPrompt(entity1, entity2, options = {}) {
  const {
    includeExamples = true
  } = options;

  // Build entity comparison section
  const comparisonSection = buildEntityComparisonSection(entity1, entity2);
  
  // Build examples section
  const examplesSection = includeExamples ? buildDisambiguationExamplesSection() : '';
  
  // Build constraints section
  const disambiguationConstraints = buildDisambiguationConstraintsSection();

  return `你是一个知识图谱实体消歧专家。你的任务是判断两个实体是否为同一实体。

${comparisonSection}

## 任务要求
1. 判断这两个实体是否为同一实体
2. 提供置信度评分（0-1）
3. 说明判断理由
4. 如果是同一实体，建议使用哪个名称作为规范名称

${examplesSection}

${disambiguationConstraints}

## 输出格式
请严格按照以下 JSON 格式输出，不要包含其他文字：

{
  "is_same": true,
  "confidence": 0.95,
  "reasoning": "判断理由",
  "recommended_canonical_name": "建议的规范名称"
}`;
}

/**
 * Build entity comparison section
 * @param {Object} entity1 - First entity
 * @param {Object} entity2 - Second entity
 * @returns {string} Formatted section
 */
function buildEntityComparisonSection(entity1, entity2) {
  const formatEntity = (entity, label) => {
    const aliasesStr = entity.aliases && entity.aliases.length > 0
      ? entity.aliases.join('、')
      : '无';
    
    const attributesStr = entity.attributes && Object.keys(entity.attributes).length > 0
      ? Object.entries(entity.attributes)
          .map(([key, value]) => `  - ${key}: ${value}`)
          .join('\n')
      : '  无';

    return `### ${label}
- **规范名称**: ${entity.canonical_name}
- **别名**: ${aliasesStr}
- **属性**:
${attributesStr}`;
  };

  return `## 实体对比

${formatEntity(entity1, '实体1')}

${formatEntity(entity2, '实体2')}`;
}

