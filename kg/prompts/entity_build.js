/**
 * Build disambiguation constraints section
 * @returns {string} Formatted section with constraints
 */
function buildDisambiguationConstraintsSection() {
  return `## 判断标准

1. **名称匹配**：
   - 规范名称完全相同 → 很可能是同一实体
   - 规范名称包含关系（如"阿里巴巴" vs "阿里巴巴集团"）→ 可能是同一实体
   - 别名重叠 → 增加同一实体的可能性
   - 名称完全不同且无别名重叠 → 很可能是不同实体

2. **属性匹配**：
   - 属性完全一致 → 增加同一实体的可能性
   - 属性互补（无冲突）→ 可能是同一实体的不同描述
   - 属性冲突 → 降低同一实体的可能性
   - 核心属性冲突（如类型、身份）→ 很可能是不同实体

3. **置信度评估**：
   - 0.9-1.0：非常确定是/不是同一实体
   - 0.7-0.9：比较确定
   - 0.5-0.7：不太确定，建议保留为两个实体
   - < 0.5：完全不确定，必须保留为两个实体

4. **推荐规范名称**：
   - 如果 is_same=true，选择更简洁、更常用的名称
   - 如果 is_same=false，返回 null
   - 优先选择已有别名更多的实体的名称（说明更常用）

5. **保守原则**：
   - 当不确定时（confidence < 0.8），倾向于判断为不同实体
   - 宁可保留重复实体，也不要错误合并不同实体
   - 属性冲突时，必须判断为不同实体`;
}

/**
 * Validate entity naming result from LLM response
 * 
 * @param {Object} result - Result to validate
 * @param {string} rawName - Original raw name
 * @returns {Object} Validation result with valid data and errors
 */
function validateEntityNamingResult(result, rawName) {
  const errors = [];

  // Validate result structure
  if (!result || typeof result !== 'object') {
    errors.push('Result must be an object');
    return { validResult: null, errors };
  }

  // Validate canonical_name
  if (!result.canonical_name || typeof result.canonical_name !== 'string') {
    errors.push('canonical_name must be a non-empty string');
  } else if (result.canonical_name.trim().length === 0) {
    errors.push('canonical_name cannot be empty or whitespace');
  } else if (result.canonical_name.length > 100) {
    errors.push('canonical_name is too long (max 100 characters)');
  }

  // Validate aliases
  if (!Array.isArray(result.aliases)) {
    errors.push('aliases must be an array');
  } else {
    // Filter out empty aliases first for validation
    const nonEmptyAliases = result.aliases.filter(a => a && typeof a === 'string' && a.trim().length > 0);
    
    // Check for invalid aliases (non-string or empty after trim)
    const invalidAliases = result.aliases.filter(a => !a || typeof a !== 'string' || a.trim().length === 0);
    if (invalidAliases.length > 0 && nonEmptyAliases.length === 0) {
      // Only error if ALL aliases are invalid
      errors.push('All aliases are invalid (must be non-empty strings)');
    }
    
    // Check for duplicate aliases (only among non-empty ones)
    if (nonEmptyAliases.length > 0) {
      const uniqueAliases = new Set(nonEmptyAliases.map(a => a.trim()));
      if (uniqueAliases.size !== nonEmptyAliases.length) {
        errors.push('Aliases contain duplicates');
      }
      
      // Check if canonical_name is in aliases
      if (result.canonical_name && nonEmptyAliases.some(a => a.trim() === result.canonical_name.trim())) {
        errors.push('canonical_name should not be in aliases');
      }
    }
  }

  // Validate reasoning (optional but recommended)
  if (result.reasoning && typeof result.reasoning !== 'string') {
    errors.push('reasoning must be a string');
  }

  // If there are critical errors, return null
  if (errors.length > 0) {
    return { validResult: null, errors };
  }

  const validResult = {
    canonical_name: result.canonical_name.trim(),
    aliases: result.aliases.filter(a => a && a.trim().length > 0).map(a => a.trim()),
    reasoning: result.reasoning || ''
  };

  return { validResult, errors };
}

/**
 * Validate entity disambiguation result from LLM response
 * 
 * @param {Object} result - Result to validate
 * @returns {Object} Validation result with valid data and errors
 */
function validateDisambiguationResult(result) {
  const errors = [];

  // Validate result structure
  if (!result || typeof result !== 'object') {
    errors.push('Result must be an object');
    return { validResult: null, errors };
  }

  // Validate is_same
  if (typeof result.is_same !== 'boolean') {
    errors.push('is_same must be a boolean');
  }

  // Validate confidence
  if (typeof result.confidence !== 'number') {
    errors.push('confidence must be a number');
  } else if (result.confidence < 0 || result.confidence > 1) {
    errors.push(`confidence must be between 0 and 1, got ${result.confidence}`);
  }

  // Validate reasoning
  if (!result.reasoning || typeof result.reasoning !== 'string') {
    errors.push('reasoning must be a non-empty string');
  }

  // Validate recommended_canonical_name
  if (result.is_same === true) {
    if (!result.recommended_canonical_name || typeof result.recommended_canonical_name !== 'string') {
      errors.push('recommended_canonical_name must be provided when is_same=true');
    }
  } else if (result.is_same === false) {
    if (result.recommended_canonical_name !== null && result.recommended_canonical_name !== undefined) {
      errors.push('recommended_canonical_name should be null when is_same=false');
    }
  }

  // If there are critical errors, return null
  if (errors.length > 0) {
    return { validResult: null, errors };
  }

  const validResult = {
    is_same: result.is_same,
    confidence: result.confidence,
    reasoning: result.reasoning,
    recommended_canonical_name: result.is_same ? result.recommended_canonical_name : null
  };

  return { validResult, errors };
}

/**
 * Get prompt statistics (for token estimation)
 * 
 * @param {string} prompt - The prompt text
 * @returns {Object} Statistics about the prompt
 */
function getPromptStats(prompt) {
  const lines = prompt.split('\n').length;
  const chars = prompt.length;
  // Rough token estimation: ~4 chars per token for Chinese text
  const estimatedTokens = Math.ceil(chars / 4);

  return {
    lines,
    chars,
    estimatedTokens
  };
}

/**
 * Determine if entity name needs LLM standardization
 * 
 * @param {string} name - Entity name to check
 * @param {number} samplingRate - Random sampling rate (0-1), default 0.5
 * @returns {boolean} Whether to use LLM standardization
 */
function shouldUseLLMStandardization(name, samplingRate = 0.5) {
  // Always use LLM if name is not well-formed
  if (!isWellFormedName(name)) {
    return true;
  }
  
  // Random sampling for quality improvement
  return Math.random() < samplingRate;
}

/**
 * Check if entity name is well-formed
 * 
 * @param {string} name - Entity name to check
 * @returns {boolean} Whether the name is well-formed
 */
function isWellFormedName(name) {
  if (!name || typeof name !== 'string') {
    return false;
  }
  
  const trimmed = name.trim();
  
  // Check for empty or too short
  if (trimmed.length === 0 || trimmed.length < 2) {
    return false;
  }
  
  // Check for excessive whitespace
  if (/\s{2,}/.test(trimmed)) {
    return false;
  }
  
  // Check for special characters that indicate poor formatting
  if (/[!@#$%^&*()+=\[\]{};':"\\|,.<>?~`]/.test(trimmed)) {
    return false;
  }
  
  // Check for redundant words
  const redundantWords = ['的', '了', '事件', '情况', '现象'];
  if (redundantWords.some(word => trimmed.endsWith(word))) {
    return false;
  }
  
  return true;
}

